// Write wawoff2's WOFF2 decoder as an ES module postext-pdf owns
// (`woff2Binding.js`), into dist (the build) or src (the tests).
//
// wawoff2 ships an emscripten glue file that picks its environment from the
// host's globals: Node when `process.versions.node` is a string, the web
// when `window` is an object. Only the Node branch assigns
// `module.exports`, and wawoff2 waits for `onRuntimeInitialized` on that
// export. A bundler or a CDN that builds the glue as a web module (esm.sh
// since its `process` polyfill stopped naming a Node version, Vite,
// webpack) hands wawoff2 an empty export: its decoder never resolves, and
// every PDF that asks for a WOFF2 font waits for ever.
//
// The module written here runs the same glue inside a function whose
// locals hide those globals, so it takes no branch at all: the WebAssembly
// is a data: URI decoded with `atob`, nothing is fetched or required, and
// the runtime it builds is the one handed back. The same code in Node, a
// browser page, a worker and any CDN or bundler.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const glue = require.resolve('wawoff2/build/decompress_binding.js');
const version = JSON.parse(readFileSync(path.join(path.dirname(glue), '..', 'package.json'), 'utf8')).version;
const code = readFileSync(glue, 'utf8');
if (!code.includes('data:application/octet-stream;base64,')) {
  throw new Error('wawoff2: the decoder glue no longer embeds its WebAssembly; woff2-binding.mjs needs a look');
}

const HIDDEN = ['window', 'document', 'self', 'importScripts', 'process', 'require', 'module', 'exports', '__dirname', '__filename', 'Buffer'];

const out = `// Generated by postext-pdf scripts/woff2-binding.mjs from wawoff2 ${version}
// (MIT, https://github.com/fontello/wawoff2; Google's woff2, MIT). Do not edit.
/* eslint-disable */
export default function instantiateWoff2() {
  return new Promise(function (resolve, reject) {
    var Module = {
      onRuntimeInitialized: function () { resolve(Module); },
      onAbort: function (what) { reject(new Error('WOFF2 decoder: ' + what)); },
    };
    var ${HIDDEN.join(', ')};
${code}
  });
}
`;

const targets = process.argv.slice(2);
if (!targets.length) targets.push('dist');
for (const dir of targets) {
  const target = new URL(`../${dir}/woff2Binding.js`, import.meta.url);
  mkdirSync(new URL('.', target), { recursive: true });
  writeFileSync(target, out);
}
